"""Gaia-seeded, adaptive, iterative joint PSF photometry in crowded fields.

Typical use (a notebook, with the Rubin stack set up)::

    import lsst.meas.crowd as crowd

    cfg = crowd.make_config(crowd.V5_TESTING_CONFIG)
    sess = crowd.prepare_session(visit=..., detector=..., cutouts=["1000,1000,300"],
                                 pad=20, psf_source="visit")
    crowd.attach_gaia(sess)
    runs = crowd.run_session_gaia(sess, cfg, out_dir="results")
    run = runs[next(iter(runs))]
    crowd.plot_final_comparison(run)          # data | model | residual | residual/sigma
    crowd.plot_source_cutouts(run)            # per-source cutouts, cross-sections, magnitudes
    tbl = crowd.measure_photometry(run)       # astropy Table with PSF / aperture magnitudes

Submodules are imported on first use, so ``import lsst.meas.crowd.fastKernels`` (or the
photometry helpers) works without importing the whole pipeline.
"""

